"""The `flutter` export target: resolution-aware layout, Dart constants, pubspec snippet, sections, runtime.

The real-engine proof (sizes, chosen variants, centerSlice units, crisp corners, goldens) is
demos/flutter (`./regenerate.sh && flutter test`).
"""
import json
import re

import pytest
from PIL import Image

from conftest import ROOT
from ninekit import NinekitError
from ninekit.cli import main as cli_main
from ninekit.exporters import flutter as fl
from ninekit.exporters.flutter import dart_class, dart_member, dp_mismatches, export
from ninekit.render import build

BASICS = ROOT / "examples" / "basics" / "basics.yaml"


@pytest.fixture(scope="module")
def basics(tmp_path_factory):
    """examples/basics built at scales 1, 2, 3 (once for the module)."""
    return build(BASICS, out=tmp_path_factory.mktemp("basics"))


def _app(tmp_path):
    app = tmp_path / "app"
    app.mkdir()
    (app / "pubspec.yaml").write_text("name: app\n")
    return app


def _manifest(tmp_path, name, pieces, scales=(3,)):
    """A hand-made manifest: pieces = {piece: {"outputs": {output: (w, h)}, "stack": [...], ...}}."""
    folder = tmp_path / name
    folder.mkdir()
    single = len(scales) == 1
    out = {}
    for pname, p in pieces.items():
        outputs = {}
        for o, (w, h) in p["outputs"].items():
            for s in scales:
                f = f"{pname}{'' if o == 'main' else '_' + o}{'' if single else f'@{s}x'}.png"
                Image.new("RGBA", (w * s, h * s), (200, 100, 50, 255)).save(folder / f)
                sl = p.get("slice")
                outputs.setdefault(o, {})[str(s)] = {
                    "file": f, "size_px": [w * s, h * s], "slice_px": None if sl is None else [v * s for v in sl]}
        w, h = next(iter(p["outputs"].values()))
        out[pname] = {"size": [w, h], "slice": p.get("slice"), "stretch": ["stretch", "stretch"],
                      "content": None, "overhang": None, "mode": "color",
                      "stack": p.get("stack", list(p["outputs"])), "outputs": outputs}
    m = {"ninekit": 1, "name": name, "generator": "ninekit test", "scales": list(scales), "pieces": out}
    (folder / "ninekit.json").write_text(json.dumps(m))
    return folder / "ninekit.json"


def _section(text, name):
    m = re.search(rf"^// ninekit:begin {name}\n(.*?)^// ninekit:end {name}\n", text, re.S | re.M)
    assert m, f"no section {name}"
    return m.group(1)


def test_resolution_aware_layout_without_scale_suffix(basics, tmp_path, capsys):
    app = _app(tmp_path)
    out = app / "assets" / "ui"
    written = export(basics.manifest_path, out)
    src = basics.out_dir
    for piece, name in [("panel", "panel.png"), ("tab", "tab_frame.png"), ("tab", "tab_face.png")]:
        stem = name[:-4]
        assert (out / name).read_bytes() == (src / f"{stem}@1x.png").read_bytes()
        assert (out / "2.0x" / name).read_bytes() == (src / f"{stem}@2x.png").read_bytes()
        assert (out / "3.0x" / name).read_bytes() == (src / f"{stem}@3x.png").read_bytes()
    assert not [p for p in out.rglob("*") if "@" in p.name]
    assert sorted(p.name for p in out.iterdir() if p.is_dir()) == ["2.0x", "3.0x"]
    dart = app / "lib" / "ninekit" / "ninekit_sprites.dart"
    assert dart in written and not (app / "lib" / "ninekit" / "ninekit.dart").exists()
    # scale 1 present: the folder is enough
    assert capsys.readouterr().out.strip() == "flutter:\n  assets:\n    - assets/ui/"


def test_dart_constants(basics, tmp_path):
    app = _app(tmp_path)
    export(basics.manifest_path, app / "assets" / "ui")
    text = (app / "lib" / "ninekit" / "ninekit_sprites.dart").read_text()
    assert text.startswith("// GENERATED by ninekit")
    assert "class NineSprite" in text and "enum NineStretch" in text      # self-contained data classes
    sec = _section(text, "basics")
    assert "abstract final class Basics {" in sec
    m = basics.manifest["pieces"]
    panel = m["panel"]
    # the panel image: asset key, logical size, centerSlice = piece-level dp slice, every file's exact px
    w, h = panel["size"]
    l, t, r, b = panel["slice"]
    block = sec[sec.index("static const NineImage panelMain"):sec.index("static const NineSprite panel ")]
    assert "asset: 'assets/ui/panel.png'" in block
    assert f"size: Size({fl._num(w)}, {fl._num(h)})" in block
    assert f"centerSlice: Rect.fromLTRB({fl._num(l)}, {fl._num(t)}, {fl._num(w - r)}, {fl._num(h - b)})" in block
    for sk, e in panel["outputs"]["main"].items():
        sp = e["slice_px"]
        assert (f"NineVariant(scale: {sk}, width: {e['size_px'][0]}, height: {e['size_px'][1]}, "
                f"slice: EdgeInsets.fromLTRB({sp[0]}, {sp[1]}, {sp[2]}, {sp[3]}))") in block
    sprite = sec[sec.index("static const NineSprite panel "):]
    sprite = sprite[:sprite.index(");") + 2]
    assert "content: EdgeInsets.fromLTRB(10, 8, 10, 14)" in sprite
    assert "overhang: EdgeInsets.fromLTRB(0, 0, 0, 3)" in sprite
    assert "layers: [panelMain]" in sprite
    # stack order, drawn-whole pieces, shade mode, tile axes
    assert "layers: [tabFrame, tabFace]" in sec
    badge = sec[sec.index("static const NineImage badgeMain"):sec.index("static const NineSprite badge ")]
    assert "centerSlice" not in badge and "slice:" not in badge
    assert "mode: NineMode.shade" in sec
    assert "stretchX: NineStretch.tile" in sec and "stretchY: NineStretch.tile" in sec
    # y-fixed pieces (pill, bars): the value is written and the enum declares it, or the Dart won't compile
    assert m["pill"]["stretch"] == ["stretch", "fixed"]
    pill = sec[sec.index("static const NineSprite pill "):]
    assert "stretchY: NineStretch.fixed," in pill[:pill.index(");")]
    enum = re.search(r"enum NineStretch \{([^}]*)\}", text).group(1)
    assert {v.strip() for v in enum.split(",")} == {"stretch", "tile", "fixed"}
    assert re.search(r"static const List<NineSprite> all = \[badge, barFill, barTrack, panel, pill, scifi, "
                     r"shadeButton, stone, tab\];", sec)


def test_without_scale_1_main_files_are_absent_and_listed(tmp_path, capsys):
    mpath = _manifest(tmp_path, "btns", {"btn": {"outputs": {"frame": (20, 10), "face": (20, 10)},
                                                 "slice": [4, 3, 4, 3]}}, scales=(3,))
    app = _app(tmp_path)
    out = app / "assets" / "ui"
    export(mpath, out)
    # never a 3x file in the 1x slot: Flutter would take it for 1x
    assert not (out / "btn_frame.png").exists() and not (out / "btn_face.png").exists()
    assert (out / "3.0x" / "btn_frame.png").is_file() and (out / "3.0x" / "btn_face.png").is_file()
    assert capsys.readouterr().out.strip() == ("flutter:\n  assets:\n    - assets/ui/btn_face.png\n"
                                               "    - assets/ui/btn_frame.png")
    sec = _section((app / "lib" / "ninekit" / "ninekit_sprites.dart").read_text(), "btns")
    assert "asset: 'assets/ui/btn_frame.png'" in sec                     # the (missing) main key
    assert "NineVariant(scale: 3, width: 60, height: 30, slice: EdgeInsets.fromLTRB(12, 9, 12, 9))" in sec
    assert "centerSlice: Rect.fromLTRB(4, 3, 16, 7)" in sec


def test_scale_filter_and_stale_variants(basics, tmp_path, capsys):
    app = _app(tmp_path)
    out = app / "assets" / "ui"
    export(basics.manifest_path, out)
    export(basics.manifest_path, out, scale=2)
    # only 2.0x stays (the main and 3.0x files of the earlier export are removed): explicit listing
    assert (out / "2.0x" / "panel.png").is_file()
    assert not (out / "panel.png").exists() and not (out / "3.0x" / "panel.png").exists()
    printed = capsys.readouterr().out
    assert "    - assets/ui/panel.png" in printed
    sec = _section((app / "lib" / "ninekit" / "ninekit_sprites.dart").read_text(), "basics")
    assert "NineVariant(scale: 2," in sec and "NineVariant(scale: 1," not in sec
    with pytest.raises(NinekitError, match="--scale 5"):
        export(basics.manifest_path, out, scale=5)


def test_fractional_scale_folder_and_template_folders(tmp_path):
    assert fl.variant_dir("2") == "2.0x" and fl.variant_dir("1.5") == "1.5x" and fl.variant_dir("3") == "3.0x"
    assert fl.flutter_name("ui/card@1.5x.png", "1.5") == "ui/card.png"
    assert fl.variant_path("ui/card.png", "1.5") == "ui/1.5x/card.png"
    assert fl.variant_path("ui/card.png", "1") == "ui/card.png"
    assert fl.pubspec_snippet(["ui/card.png", "top.png"], "assets/", True) == \
        "flutter:\n  assets:\n    - assets/\n    - assets/ui/"


def test_composite_main_is_not_stacked(tmp_path):
    mpath = _manifest(tmp_path, "round", {"btnc": {"outputs": {"frame": (10, 10), "face": (10, 10),
                                                               "main": (10, 10)},
                                                   "stack": ["frame", "face", "main"]}})
    app = _app(tmp_path)
    export(mpath, app / "assets" / "ui")
    sec = _section((app / "lib" / "ninekit" / "ninekit_sprites.dart").read_text(), "round")
    assert "layers: [btncFrame, btncFace]," in sec and "composite: btncMain," in sec


def test_runtime_flag_copies_the_adapter(basics, tmp_path):
    app = _app(tmp_path)
    written = export(basics.manifest_path, app / "assets" / "ui", runtime=True)
    rt = app / "lib" / "ninekit" / "ninekit.dart"
    assert rt in written
    assert rt.read_bytes() == (ROOT / "src" / "ninekit" / "adapters" / "flutter" / "ninekit.dart").read_bytes()
    text = rt.read_text()
    for name in ("class NineSliceBox", "class NineSliceButton", "class NineRamp", "precacheNineSprite",
                 "export 'ninekit_sprites.dart';"):
        assert name in text


def test_manifests_share_one_dart_file(basics, tmp_path):
    app = _app(tmp_path)
    other = _manifest(tmp_path, "zz_other", {"card": {"outputs": {"main": (8, 8)}}})
    export(basics.manifest_path, app / "assets" / "ui" / "basics")
    export(other, app / "assets" / "ui" / "other")
    dart = app / "lib" / "ninekit" / "ninekit_sprites.dart"
    first = dart.read_text()
    assert "asset: 'assets/ui/basics/panel.png'" in _section(first, "basics")
    assert "abstract final class ZzOther" in _section(first, "zz_other")
    export(basics.manifest_path, app / "assets" / "ui" / "basics")      # re-export keeps the other section
    assert dart.read_text() == first
    assert first.count("class NineSprite {") == 1


def test_refuses_a_foreign_dart_file_and_class_clashes(basics, tmp_path):
    app = _app(tmp_path)
    dart = app / "lib" / "ninekit" / "ninekit_sprites.dart"
    dart.parent.mkdir(parents=True)
    dart.write_text("// mine\n")
    with pytest.raises(NinekitError, match="not written by ninekit"):
        export(basics.manifest_path, app / "assets" / "ui")
    dart.unlink()
    a = _manifest(tmp_path, "my_ui", {"a": {"outputs": {"main": (4, 4)}}})
    b = _manifest(tmp_path, "my-ui", {"b": {"outputs": {"main": (4, 4)}}})
    export(a, app / "assets" / "a")
    with pytest.raises(NinekitError, match="Dart class MyUi"):
        export(b, app / "assets" / "b")


def test_unknown_manifest_keys_are_ignored(tmp_path):
    mpath = _manifest(tmp_path, "extra", {"card": {"outputs": {"main": (8, 6)}, "slice": [2, 2, 2, 2]}})
    m = json.loads(mpath.read_text())
    m["pieces"]["card"]["design_size"] = [40, 6]           # e.g. the size as designed, before compaction
    m["something_new"] = {"x": 1}
    mpath.write_text(json.dumps(m))
    app = _app(tmp_path)
    export(mpath, app / "assets")
    sec = _section((app / "lib" / "ninekit" / "ninekit_sprites.dart").read_text(), "extra")
    assert "size: Size(8, 6)," in sec and "design_size" not in sec and "40" not in sec


def test_dart_identifier_clash_is_an_error(tmp_path):
    mpath = _manifest(tmp_path, "clash", {"tab": {"outputs": {"frame": (4, 4)}},
                                          "tab_frame": {"outputs": {"face": (4, 4)}}}, scales=(1, 2))
    # tab/frame -> tabFrame; piece tab_frame -> tabFrame too
    with pytest.raises(NinekitError, match="tabFrame"):
        export(mpath, _app(tmp_path) / "assets")


def test_identifiers():
    assert dart_member("btn_mint_light") == "btnMintLight"
    assert dart_member("bar-track.v2") == "barTrackV2"
    assert dart_member("3d_box") == "n3dBox"
    assert dart_member("class") == "class_"
    assert dart_class("gumdrop_buttons") == "GumdropButtons"
    assert dart_class("nine_sprite") == "NineSpriteSprites"        # never a runtime type's name


def test_outside_a_flutter_project(basics, tmp_path, capsys):
    out = tmp_path / "export" / "ui"
    export(basics.manifest_path, out)
    dart = out / "ninekit_sprites.dart"
    assert "asset: 'ui/panel.png'" in dart.read_text()
    assert "no pubspec.yaml" in capsys.readouterr().out


def test_cli(basics, tmp_path, capsys):
    app = _app(tmp_path)
    assert cli_main(["export", str(basics.manifest_path), "--target", "flutter", "-o",
                     str(app / "assets" / "ui"), "--runtime"]) == 0
    out = capsys.readouterr().out
    assert "    - assets/ui/" in out and "ninekit.dart" in out and "wrote" in out


def test_files_are_dp_times_scale(basics):
    """One logical centerSlice is exact in every file only if each file's px are the piece's dp x scale."""
    bad = dp_mismatches(basics.manifest)
    assert not bad, bad
