"""The `flutter` export target (DESIGN 7): resolution-aware assets, Dart constants and the Dart runtime.

`ninekit export out/ninekit.json --target flutter -o <app>/assets/ui [--runtime]` writes

* the PNGs in Flutter's resolution-aware layout, without the `@<s>x` suffix: scale 1 is the main asset
  (`assets/ui/card.png`), scale s goes to `assets/ui/<s>x/card.png` (`2.0x`, `3.0x`, `1.5x`);
* `lib/ninekit/ninekit_sprites.dart`: the data classes (`NineSprite`, `NineImage`, `NineVariant`) and, per
  manifest, an `abstract final class` (`basics` -> `Basics`) with one const per piece (`Basics.panel`) and one
  per output image (`Basics.panelMain`, `Basics.tabFrame`): asset key, logical size, `centerSlice`, content
  padding, overhang, stack order and every variant's exact `size_px` / `slice_px`;
* with `--runtime`, `lib/ninekit/ninekit.dart` (from `ninekit/adapters/flutter/`): `NineSliceBox`,
  `NineSliceButton`, `NineRamp` (shade mode) and `precacheNineSprite`; it re-exports the sprites file.

The Flutter app is the first folder at or above the output folder holding a `pubspec.yaml`: asset keys are
relative to it and the Dart goes to its `lib/ninekit/`. Outside a Flutter project the output folder's parent
stands in for the app (keys start with the output folder's name) and the Dart is written into the output folder.

Specs without scale 1. Flutter treats the main asset as 1.0x, so a 3x file there would claim to be 1x (three
times too large, wrong `centerSlice`). The exporter never puts a non-1x file in the main slot and never
resamples: the main file is simply absent and the pubspec lists each main asset path explicitly (Flutter
allows a missing main file when variants exist; a folder entry would not see them). Every device then gets a
real variant with its real scale: below the lowest scale Flutter falls back to that lowest variant (scale 3 at
DPR 1, drawn at a third), so logical sizes stay right. With scale 1 present, the pubspec lists the folders.

`centerSlice` (for a plain `Image.asset(..., centerSlice:, fit: BoxFit.fill)`) is in logical units: Flutter's
`paintImage` multiplies it by the chosen variant's scale (`_scaleRect(centerSlice, scale)`; measured in
demos/flutter/test/center_slice_test.dart). It is the piece-level dp slice, exact in every file whose px
values are the dp values x scale. `NineSliceBox` draws the chosen file with that file's own `slice_px`.

Several manifests can share one app: each export rewrites only its own section of `ninekit_sprites.dart`
(`// ninekit:begin <name>` ... `// ninekit:end <name>`) and keeps the others.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from ninekit import NinekitError, __version__
from ninekit.manifest import iter_files, load_manifest, scale_key

ADAPTER_DIR = Path(__file__).resolve().parent.parent / "adapters" / "flutter"
SPRITES_FILE = "ninekit_sprites.dart"
RUNTIME_FILE = "ninekit.dart"
BANNER = "// GENERATED by ninekit"

_SECTION_RE = re.compile(r"^// ninekit:begin (\S+)\n.*?^// ninekit:end \1\n", re.S | re.M)
_CLASS_RE = re.compile(r"^abstract final class (\w+)", re.M)
_VARIANT_DIR_RE = re.compile(r"^(\d+(\.\d*)?)x$")      # flutter_tools' variant folder rule

_DART_KEYWORDS = {
    "abstract", "as", "assert", "async", "await", "base", "break", "case", "catch", "class", "const", "continue",
    "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export", "extends", "extension",
    "external", "factory", "false", "final", "finally", "for", "Function", "get", "hide", "if", "implements",
    "import", "in", "interface", "is", "late", "library", "mixin", "new", "null", "of", "on", "operator", "part",
    "required", "rethrow", "return", "sealed", "set", "show", "static", "super", "switch", "sync", "this",
    "throw", "true", "try", "type", "typedef", "var", "void", "when", "while", "with", "yield",
}
# Types the generated file and the runtime declare: a manifest class may not take these names.
_RESERVED_CLASSES = {
    "NineSprite", "NineImage", "NineVariant", "NineStretch", "NineMode", "NineSliceBox", "NineSliceButton",
    "NineRamp", "NineSlicePainter",
}


# --- names -------------------------------------------------------------------------------------------------

def variant_dir(sk: str) -> str:
    """Flutter's folder for a scale: "2.0x", "3.0x", "1.5x"."""
    f = float(sk)
    return f"{f:.1f}x" if f.is_integer() else f"{f:g}x"


def flutter_name(file: str, sk: str) -> str:
    """A manifest file name without its `@<s>x` token (the variant folder carries the scale)."""
    name = file.replace(f"@{sk}x", "")
    parts = [p for p in name.replace("\\", "/").split("/") if p and p != "."]
    if not parts or parts[-1].startswith("."):
        raise NinekitError(f"{file}: no file name left after removing @{sk}x")
    return "/".join(parts)


def variant_path(name: str, sk: str) -> str:
    """Where scale [sk] of [name] lives, relative to the output folder."""
    if float(sk) == 1.0:
        return name
    head, _, base = name.rpartition("/")
    return f"{head}/{variant_dir(sk)}/{base}" if head else f"{variant_dir(sk)}/{base}"


def _words(name: str) -> list[str]:
    return [w for w in re.split(r"[^0-9A-Za-z]+", name) if w]


def dart_member(name: str) -> str:
    """`btn_mint_light` -> `btnMintLight` (a valid, non-keyword Dart identifier)."""
    ws = _words(name) or ["sprite"]
    s = ws[0][:1].lower() + ws[0][1:] + "".join(w[:1].upper() + w[1:] for w in ws[1:])
    if s[0].isdigit():
        s = "n" + s
    return s + "_" if s in _DART_KEYWORDS else s


def dart_class(name: str) -> str:
    """`gumdrop_buttons` -> `GumdropButtons`."""
    ws = _words(name) or ["Sprites"]
    s = "".join(w[:1].upper() + w[1:] for w in ws)
    if s[0].isdigit():
        s = "N" + s
    return s + "Sprites" if s in _RESERVED_CLASSES else s


# --- Dart literals -----------------------------------------------------------------------------------------

def _num(v) -> str:
    f = float(v)
    if f.is_integer():
        return str(int(f))
    return f"{round(f, 4):.4f}".rstrip("0").rstrip(".")


def _str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def _ltrb(v, ctor: str = "EdgeInsets.fromLTRB") -> str:
    return f"{ctor}({', '.join(_num(x) for x in v)})"


# --- the project -------------------------------------------------------------------------------------------

def find_flutter_root(out: Path) -> Path | None:
    """The first folder at or above [out] with a pubspec.yaml (the Flutter app), or None."""
    for p in (out, *out.parents):
        if (p / "pubspec.yaml").is_file():
            return p
    return None


def center_slice(piece: dict) -> list[float] | None:
    """The logical centerSlice [left, top, right, bottom] (a rect in dp) for `Image(centerSlice:)`: the
    piece-level dp slice inside the piece-level dp size, or None for a piece drawn whole. Flutter multiplies it
    by the chosen file's scale, so it is exact in every file whose slice_px == slice_dp x scale and size_px ==
    size_dp x scale (DESIGN 3; the core snaps slices and sizes to such a dp grid)."""
    sl = piece.get("slice")
    if sl is None:
        return None
    w, h = piece["size"]
    return [sl[0], sl[1], w - sl[2], h - sl[3]]


def dp_mismatches(manifest: dict) -> list[str]:
    """Files whose px size or slices are not the piece's dp values x scale (each listed once per piece)."""
    bad = []
    for pname, piece in manifest["pieces"].items():
        w, h = piece["size"]
        sl = piece.get("slice")
        for o, per in piece["outputs"].items():
            for sk, e in sorted(per.items(), key=lambda kv: float(kv[0])):
                s = float(sk)
                want_size = [round(w * s), round(h * s)]
                want_slice = None if sl is None else [round(v * s) for v in sl]
                if e["size_px"] != want_size or e["slice_px"] != want_slice:
                    bad.append(f"{pname}/{o} @{sk}x: size_px {e['size_px']} slice_px {e['slice_px']} "
                               f"!= dp x scale {want_size} {want_slice}")
    return bad


# --- export ------------------------------------------------------------------------------------------------

def export(manifest_path, out_dir, scale=None, runtime=False) -> list[Path]:
    mpath = Path(manifest_path)
    if mpath.is_dir():
        mpath = mpath / "ninekit.json"
    manifest = load_manifest(mpath)
    out = Path(out_dir).resolve()
    want = None if scale is None else scale_key(scale)
    scales = [scale_key(s) for s in manifest.get("scales", [])]
    if want is not None and float(want) not in {float(s) for s in scales}:
        raise NinekitError(f"--scale {want}: the manifest has scales {manifest.get('scales')}")
    out.mkdir(parents=True, exist_ok=True)

    root = find_flutter_root(out)
    if root is not None:
        prefix = out.relative_to(root).as_posix()
        prefix = "" if prefix == "." else prefix + "/"
        dart_dir = root / "lib" / "ninekit"
    else:
        prefix = out.name + "/"
        dart_dir = out

    # every (piece, output) -> one flutter name; its files per scale
    names: dict[tuple[str, str], str] = {}
    owners: dict[str, tuple[str, str]] = {}
    files: dict[tuple[str, str], dict[str, dict]] = {}
    for pname, o, sk, entry in iter_files(manifest):
        if want is not None and float(sk) != float(want):
            continue
        name = flutter_name(entry["file"], sk)
        key = (pname, o)
        if names.setdefault(key, name) != name:
            raise NinekitError(f"{pname}/{o}: its files do not share one name once @<s>x is removed "
                               f"({names[key]!r} vs {name!r}); put {{scale}} in the file template")
        if owners.setdefault(name, key) != key:
            raise NinekitError(f"{name}: used by {owners[name][0]}/{owners[name][1]} and {pname}/{o}")
        files.setdefault(key, {})[sk] = entry
    if not files:
        raise NinekitError(f"{mpath}: nothing to export")

    written: list[Path] = []
    exported_scales = sorted({sk for per in files.values() for sk in per}, key=float)
    for key, per in files.items():
        name = names[key]
        for sk, entry in per.items():
            src = mpath.parent / entry["file"]
            dst = out / variant_path(name, sk)
            dst.parent.mkdir(parents=True, exist_ok=True)
            if src.resolve() != dst.resolve():
                shutil.copyfile(src, dst)
            written.append(dst)
        _remove_stale(out, name, set(per))

    mains = {k: prefix + n for k, n in names.items()}
    section = _section(manifest, files, mains, prefix, exported_scales)
    sprites_path = dart_dir / SPRITES_FILE
    _write_sprites(sprites_path, manifest["name"], dart_class(manifest["name"]), section)
    written.append(sprites_path)
    if runtime:
        dart_dir.mkdir(parents=True, exist_ok=True)
        rt = dart_dir / RUNTIME_FILE
        shutil.copyfile(ADAPTER_DIR / RUNTIME_FILE, rt)
        written.append(rt)

    print(pubspec_snippet(names.values(), prefix, has_main="1" in exported_scales))
    if root is None:
        print(f"note: no pubspec.yaml at or above {out}: asset keys start with {prefix!r} and the Dart files "
              f"are in {dart_dir}; move them to your app's lib/")
    return written


def _remove_stale(out: Path, name: str, scales: set[str]) -> None:
    """Deletes this image's files left by an earlier export at scales not exported now."""
    head, _, base = name.rpartition("/")
    folder = out / head if head else out
    if "1" not in scales and (folder / base).is_file():
        (folder / base).unlink()
    if folder.is_dir():
        for d in folder.iterdir():
            m = _VARIANT_DIR_RE.match(d.name)
            if d.is_dir() and m and scale_key(m.group(1)) not in scales and (d / base).is_file():
                (d / base).unlink()


def pubspec_snippet(names, prefix: str, has_main: bool) -> str:
    """The `flutter: assets:` lines: the folders when the main (1x) files exist, else every main path."""
    if has_main:
        entries = sorted({prefix + (n.rpartition("/")[0] + "/" if "/" in n else "") for n in names})
    else:
        entries = sorted(prefix + n for n in names)
    return "\n".join(["flutter:", "  assets:", *(f"    - {e}" for e in entries)])


def _section(manifest: dict, files: dict, assets: dict, prefix: str, scales: list[str]) -> str:
    mname = manifest["name"]
    cls = dart_class(mname)
    snippet = pubspec_snippet([a[len(prefix):] for a in assets.values()], prefix, has_main="1" in scales)
    lines = [
        f"// ninekit:begin {mname}",
        f"/// Sprites of `{mname}` ({manifest.get('generator', 'ninekit')}, scales "
        f"{', '.join(scales)}; exported by ninekit {__version__}).",
        "///",
        "/// pubspec.yaml:",
        "/// ```yaml",
        *(f"/// {ln}" for ln in snippet.splitlines()),
        "/// ```",
        f"abstract final class {cls} {{",
    ]
    members: dict[str, str] = {}

    def claim(ident: str, what: str) -> str:
        if ident in members or ident == "all":
            raise NinekitError(f"{mname}: Dart name {cls}.{ident} would be used by both "
                               f"{members.get(ident, 'the list `all`')} and {what}; rename one")
        members[ident] = what
        return ident

    sprite_names = []
    for pname, piece in manifest["pieces"].items():
        stack = [o for o in (piece.get("stack") or list(piece["outputs"])) if (pname, o) in files]
        if not stack:
            continue
        composite = "main" if "main" in stack and len(stack) > 1 else None
        layers = [o for o in stack if o != composite]
        image_ids = {}
        for o in stack:
            ident = claim(dart_member(f"{pname}_{o}"), f"{pname}/{o}")
            image_ids[o] = ident
            per = files[(pname, o)]
            variants = [{"scale": sk, **per[sk]} for sk in sorted(per, key=float)]
            cs = center_slice(piece)
            lines += [
                f"  static const NineImage {ident} = NineImage(",
                f"    piece: {_str(pname)},",
                f"    output: {_str(o)},",
                f"    asset: {_str(assets[(pname, o)])},",
                f"    size: Size({_num(piece['size'][0])}, {_num(piece['size'][1])}),",
            ]
            if cs is not None:
                lines.append(f"    centerSlice: {_ltrb(cs, 'Rect.fromLTRB')},")
            lines.append("    variants: [")
            for v in variants:
                sp = v["slice_px"]
                sl = "" if sp is None else f", slice: {_ltrb(sp)}"
                lines.append(f"      NineVariant(scale: {_num(v['scale'])}, width: {v['size_px'][0]}, "
                             f"height: {v['size_px'][1]}{sl}),")
            lines += ["    ],", "  );"]
        ident = claim(dart_member(pname), f"piece {pname}")
        sprite_names.append(ident)
        sx, sy = piece.get("stretch", ["stretch", "stretch"])
        lines += [
            f"  static const NineSprite {ident} = NineSprite(",
            f"    name: {_str(pname)},",
            f"    size: Size({_num(piece['size'][0])}, {_num(piece['size'][1])}),",
        ]
        if piece.get("slice") is not None:
            lines.append(f"    slice: {_ltrb(piece['slice'])},")
        if sx != "stretch":
            lines.append(f"    stretchX: NineStretch.{sx},")
        if sy != "stretch":
            lines.append(f"    stretchY: NineStretch.{sy},")
        if piece.get("content") is not None:
            lines.append(f"    content: {_ltrb(piece['content'])},")
        if piece.get("overhang") is not None:
            lines.append(f"    overhang: {_ltrb(piece['overhang'])},")
        if piece.get("mode", "color") != "color":
            lines.append(f"    mode: NineMode.{piece['mode']},")
        lines.append(f"    layers: [{', '.join(image_ids[o] for o in layers)}],")
        if composite:
            lines.append(f"    composite: {image_ids[composite]},")
        lines.append("  );")
    lines += [
        f"  static const List<NineSprite> all = [{', '.join(sprite_names)}];",
        "}",
        f"// ninekit:end {mname}",
        "",
    ]
    return "\n".join(lines)


def _write_sprites(path: Path, mname: str, cls: str, section: str) -> None:
    """Writes the sprites file: the shared header and every manifest's section, this one replaced."""
    sections: dict[str, str] = {}
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if not old.startswith(BANNER):
            raise NinekitError(f"{path} exists and was not written by ninekit; move it away first")
        for m in _SECTION_RE.finditer(old):
            sections[m.group(1)] = m.group(0)
    sections.pop(mname, None)
    for other, text in sections.items():
        c = _CLASS_RE.search(text)
        if c and c.group(1) == cls:
            raise NinekitError(f"manifests {other!r} and {mname!r} both map to the Dart class {cls}; rename one")
    sections[mname] = section
    header = (ADAPTER_DIR / "ninekit_sprites_header.dart").read_text(encoding="utf-8")
    body = "\n".join(sections[k] for k in sorted(sections))
    text = (f"{BANNER} (`ninekit export --target flutter`); do not edit.\n"
            "// Each export rewrites its own manifest's section below and keeps the others.\n"
            "// ignore_for_file: constant_identifier_names\n\n"
            + header.rstrip() + "\n\n" + body)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
